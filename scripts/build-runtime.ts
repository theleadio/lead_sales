// Builds public/site/runtime.js: runtime-copy + runtime-core + runtime-dom,
// types stripped with TypeScript's own transpiler, wrapped in one IIFE.
// Run: npm run build:runtime (also the prebuild step).
import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const parts = ["runtime-copy", "runtime-core", "runtime-dom"].map((n) => {
  const src = readFileSync(new URL(`../lib/sites/${n}.ts`, import.meta.url), "utf8");
  const out = ts.transpileModule(src, {
    compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.ESNext, removeComments: true },
  }).outputText;
  // Single-line relative imports are dropped (everything shares one scope); `export` is removed.
  return out.replace(/^import .*;\r?\n/gm, "").replace(/^export /gm, "").replace(/^[ \t]+/gm, "").replace(/\n{2,}/g, "\n");
});

const js = `/* generated by scripts/build-runtime.ts - do not edit */\n(function(){"use strict";\n${parts.join("\n")}})();\n`;
writeFileSync(new URL("../public/site/runtime.js", import.meta.url), js.replace(/\r\n/g, "\n"));
console.log(`public/site/runtime.js ${Buffer.byteLength(js)} bytes`);
